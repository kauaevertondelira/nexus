import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {siteURL,serveLocalSite} from './site-fixture.mjs';
const base=process.env.NEXUS_PREVIEW_URL||siteURL;
const browser=await chromium.launch({headless:true,...(process.env.NEXUS_BROWSER_PATH?{executablePath:process.env.NEXUS_BROWSER_PATH}:{})});
const output=new URL('./results/',import.meta.url);await fs.mkdir(output,{recursive:true});
const errors=[];
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce',serviceWorkers:'block'});
  if(base===siteURL)await serveLocalSite(context);
  await context.addInitScript(()=>{
    const canvas=document.createElement('canvas');canvas.width=640;canvas.height=480;
    const ctx=canvas.getContext('2d');window.testSensor={present:false,deny:false,tracks:[]};
    setInterval(()=>{ctx.fillStyle='#505050';ctx.fillRect(0,0,640,480);if(window.testSensor.present){ctx.fillStyle='#e6c2aa';ctx.fillRect(140,130,350,210);}},40);
    Object.defineProperty(navigator.mediaDevices,'getUserMedia',{value:async()=>{
      if(window.testSensor.deny)throw new DOMException('Negada no teste','NotAllowedError');
      const stream=canvas.captureStream(25);window.testSensor.tracks.push(...stream.getTracks());return stream;
    }});
  });
  const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
  await page.goto(new URL('public/pages/producao.html?demo=1',base).href);
  await page.waitForSelector('#production-asset');
  await page.screenshot({path:fileURLToPath(new URL('producao-desktop.png',output)),fullPage:true});
  await page.locator('[data-action="production-new"][data-id="M-204"]').click();
  await page.locator('#field-label').fill('Teste de passagens');
  await page.locator('#simple-form').evaluate(form=>form.requestSubmit());
  await page.waitForSelector('#camera-start');
  await page.locator('#camera-start').click();await page.locator('#camera-calibrate:not([disabled])').waitFor();
  await page.locator('#camera-calibrate').click();
  await page.waitForFunction(()=>document.querySelector('#camera-status')?.textContent.includes('Sensor pronto'));
  await page.locator('#production-video').evaluate(video=>video.dataset.identity='preservado');
  await page.evaluate(()=>window.testSensor.present=true);
  await page.waitForFunction(()=>document.querySelector('#camera-session-count')?.textContent==='1');
  await page.waitForTimeout(1700);
  assert.equal(await page.locator('#camera-session-count').textContent(),'1','Objeto parado contou mais de uma vez');
  assert.equal(await page.locator('#production-video').getAttribute('data-identity'),'preservado','Realtime recriou o vídeo');
  await page.evaluate(()=>window.testSensor.present=false);
  await page.waitForFunction(()=>document.querySelector('#camera-status')?.textContent.includes('Sensor pronto'));
  await page.evaluate(()=>window.testSensor.present=true);
  await page.waitForFunction(()=>document.querySelector('#camera-session-count')?.textContent==='2');
  await page.screenshot({path:fileURLToPath(new URL('sensor-desktop.png',output))});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:fileURLToPath(new URL('sensor-celular.png',output))});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Página ultrapassou a tela do celular');
  await page.locator('#camera-pause').click();
  assert.ok(await page.evaluate(()=>window.testSensor.tracks.every(t=>t.readyState==='ended')),'Pausar não liberou a câmera');
  await page.locator('summary').click();await page.locator('#camera-manual').click();
  await page.waitForFunction(()=>document.querySelector('#camera-session-count')?.textContent==='3');
  await page.locator('#camera-finish').click();await page.locator('#modal-root').waitFor({state:'detached'});
  const saved=await page.evaluate(()=>({total:Nexus.productionCount('M-204'),events:Object.values(Nexus.data.production_events['M-204']),sessions:Object.values(Nexus.data.production_sessions)}));
  assert.equal(saved.total,3);assert.equal(saved.events.filter(v=>v.source==='camera').length,2);assert.equal(saved.events.filter(v=>v.source==='manual').length,1);assert.equal(saved.sessions[0].status,'closed');
  await page.selectOption('#production-asset','M-204');
  await page.reload();await page.waitForSelector('#production-asset');
  assert.equal(await page.evaluate(()=>Nexus.productionCount('M-204')),3,'Recarregar perdeu o total');
  await page.screenshot({path:fileURLToPath(new URL('producao-celular.png',output)),fullPage:true});
  // Negação de permissão deve produzir uma mensagem útil e nenhum evento.
  await page.locator('[data-action="production-new"][data-id="M-204"]').click();
  await page.locator('#simple-form').evaluate(form=>form.requestSubmit());await page.waitForSelector('#camera-start');
  await page.locator('#camera-start').click();await page.locator('#camera-calibrate:not([disabled])').waitFor();
  await page.locator('[data-action="close-modal"]').first().click();
  assert.ok(await page.evaluate(()=>window.testSensor.tracks.every(t=>t.readyState==='ended')),'Fechar não liberou a câmera ativa');
  await page.locator('[data-action="production-camera"]').click();await page.waitForSelector('#camera-start');
  await page.evaluate(()=>window.testSensor.deny=true);await page.locator('#camera-start').click();
  await page.waitForFunction(()=>document.querySelector('#camera-error')?.textContent.includes('negado'));
  assert.equal(await page.evaluate(()=>Nexus.productionCount('M-204')),3);
  await page.locator('[data-action="close-modal"]').first().click();
  assert.ok(await page.evaluate(()=>window.testSensor.tracks.every(t=>t.readyState==='ended')));
  assert.deepEqual(errors,[]);
  console.log('PASS · câmera com vídeo controlado: 2 passagens, objeto parado, +1 manual, permissão negada, pausa, encerramento, recarga e viewport 390 px.');
}finally{await browser.close();}
